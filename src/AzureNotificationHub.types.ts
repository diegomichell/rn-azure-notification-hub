/**
 * Type declarations for `rn-azure-notification-hub`.
 *
 * The shapes here mirror the Azure Notification Hubs *installation* model that both native SDKs
 * are built around:
 *
 * - iOS — [`MSInstallation`](https://github.com/Azure/azure-notificationhubs-ios)
 * - Android — [`Installation`](https://github.com/Azure/azure-notificationhubs-android)
 */

/**
 * The push platform an installation is registered against.
 *
 * On iOS this is always `apns` and cannot be changed. On Android the SDK defaults to `fcmv1`,
 * and it can be overridden with {@link setPlatformAsync} for hubs still configured for the
 * legacy `gcm` credential.
 */
export type InstallationPlatform =
  'apns' | 'fcm' | 'fcmv1' | 'gcm' | 'wns' | 'mpns' | 'adm' | 'baidu';

/**
 * `UNAuthorizationOptions` values that the iOS SDK requests when {@link startAsync} runs.
 *
 * @platform ios
 */
export type AuthorizationOption =
  | 'badge'
  | 'sound'
  | 'alert'
  | 'carPlay'
  | 'criticalAlert'
  | 'providesAppNotificationSettings'
  | 'provisional';

/**
 * A per-device notification template. Templates let the backend send one payload that the hub
 * expands per platform, so you can broadcast without knowing whether a device is on APNs or FCM.
 *
 * @see https://learn.microsoft.com/azure/notification-hubs/notification-hubs-templates-cross-platform-push-messages
 */
export type InstallationTemplate = {
  /**
   * The platform-native payload, as a JSON string, with `$(propertyName)` expression placeholders.
   *
   * @example
   * ```json
   * "{\"aps\":{\"alert\":\"$(message)\"}}"
   * ```
   */
  body: string;

  /**
   * Tags that target this template specifically. A notification sent to one of these tags is
   * delivered through this template rather than the installation's native registration.
   */
  tags?: string[];

  /**
   * Extra headers sent with the template. Required for WNS and MPNS, unused for APNs and FCM.
   */
  headers?: Record<string, string>;
};

/**
 * A snapshot of the installation record this device is registered with.
 *
 * Reads come from the SDK's local cache, which is the same record the SDK uploads. It can be
 * momentarily ahead of the hub while a save is in flight — see {@link addInstallationSavedListener}
 * to observe when the hub has actually accepted it.
 */
export type Installation = {
  /** Unique identifier for this device's installation. Generated by the SDK unless you set one. */
  installationId: string | null;

  /**
   * The platform push handle: the APNs device token (lowercase hex) on iOS, or the FCM
   * registration token on Android. `null` until the OS hands the token to the SDK.
   */
  pushChannel: string | null;

  /** The platform this installation is registered against. */
  platform: InstallationPlatform | null;

  /** The user identifier associated with this installation, if one was set. */
  userId: string | null;

  /** Tags this installation is subscribed to. */
  tags: string[];

  /** Templates registered on this installation, keyed by template name. */
  templates: Record<string, InstallationTemplate>;

  /**
   * ISO-8601 timestamp at which the hub should expire this installation, if one was set.
   */
  expirationTime: string | null;
};

/**
 * Options for {@link startAsync}.
 *
 * Pass either `connectionString` + `hubName` to talk to Azure directly, or
 * `installationManagement: true` to route installation upserts through your own backend.
 */
export type NotificationHubConfig = {
  /**
   * The hub's **listen-only** access policy connection string
   * (`DefaultListenSharedAccessSignature`).
   *
   * Required unless {@link NotificationHubConfig.installationManagement} is `true`.
   *
   * > **Never ship a `Manage` or `Send` connection string in an app bundle.** Anyone can extract
   * > it. Prefer {@link NotificationHubConfig.installationManagement} when you can.
   */
  connectionString?: string;

  /** The Notification Hub name. Required unless `installationManagement` is `true`. */
  hubName?: string;

  /**
   * Route installation upserts through your own backend instead of contacting Azure from the
   * device. When enabled, the module emits {@link InstallationUpsertRequest} events instead of
   * calling the hub, and you must acknowledge each one with {@link completeInstallationUpsert}.
   *
   * This is how you avoid embedding a connection string in the app at all.
   *
   * @default false
   */
  installationManagement?: boolean;

  /**
   * How long (ms) the native side waits for {@link completeInstallationUpsert} before failing an
   * upsert. Only used when `installationManagement` is `true`.
   *
   * @default 30000
   */
  installationUpsertTimeout?: number;

  /**
   * Which notification authorization options the iOS SDK requests when it starts.
   *
   * Starting the SDK triggers the system permission prompt, so call {@link startAsync} at a point
   * in your UX where that prompt makes sense.
   *
   * @default ['alert', 'sound', 'badge']
   * @platform ios
   */
  authorizationOptions?: AuthorizationOption[];
};

/**
 * A push notification handed to the app by the native SDK.
 */
export type NotificationPayload = {
  /** Notification title, if the payload carried one. */
  title: string | null;

  /** Notification body, if the payload carried one. */
  body: string | null;

  /**
   * The full payload.
   *
   * On iOS this is the complete APNs `userInfo` dictionary (including the `aps` key). On Android
   * it is `RemoteMessage.getData()`, so values are always strings.
   */
  data: Record<string, any>;

  /**
   * `true` when the notification arrived while the JavaScript runtime was not yet listening and
   * was replayed on startup.
   *
   * @platform android
   */
  buffered?: boolean;
};

/**
 * Emitted after the hub (or your custom backend) accepted an installation upsert.
 */
export type InstallationSavedEvent = {
  installation: Installation;
};

/**
 * Emitted when an installation upsert failed.
 */
export type InstallationSaveFailedEvent = {
  /** The installation the SDK tried to save, when the platform reports it. */
  installation: Installation | null;
  /** Human-readable failure reason. */
  message: string;
  /** Platform error code, when one is available. */
  code: string | null;
};

/**
 * Emitted in `installationManagement` mode when the SDK wants an installation persisted.
 *
 * Send `installation` to your backend, then call {@link completeInstallationUpsert} with the
 * `requestId` — passing an error message if it failed. Failing to respond within
 * {@link NotificationHubConfig.installationUpsertTimeout} is treated as a failure.
 */
export type InstallationUpsertRequest = {
  /** Opaque id to pass back to {@link completeInstallationUpsert}. */
  requestId: string;
  /** The installation to persist. */
  installation: Installation;
};

/**
 * Emitted on iOS once the user answers the notification authorization prompt that
 * {@link startAsync} triggers.
 *
 * @platform ios
 */
export type AuthorizationEvent = {
  granted: boolean;
  message: string | null;
};

/** Status of the OS-level notification permission. */
export type PermissionStatus = 'granted' | 'denied' | 'undetermined';

/**
 * The result of {@link getPermissionsAsync} and {@link requestPermissionsAsync}.
 */
export type NotificationPermissions = {
  status: PermissionStatus;
  granted: boolean;
  /** `false` once the OS will no longer show the prompt (the user must use Settings). */
  canAskAgain: boolean;
  /**
   * iOS authorization options the user actually granted.
   *
   * @platform ios
   */
  ios?: {
    allowsAlert: boolean;
    allowsBadge: boolean;
    allowsSound: boolean;
    allowsCriticalAlerts: boolean;
    allowsAnnouncements: boolean;
    providesAppNotificationSettings: boolean;
    /** `true` when authorization was granted provisionally (quiet notifications). */
    provisional: boolean;
  };
};

/**
 * The event map of the native module. Use the `add*Listener` helpers rather than subscribing to
 * these names directly.
 */
export type AzureNotificationHubModuleEvents = {
  onNotificationReceived: (event: NotificationPayload) => void;
  onInstallationSaved: (event: InstallationSavedEvent) => void;
  onInstallationSaveFailed: (event: InstallationSaveFailedEvent) => void;
  onInstallationUpsertRequested: (event: InstallationUpsertRequest) => void;
  onAuthorizationRequested: (event: AuthorizationEvent) => void;
};
